import { HttpException, HttpStatus } from '@nestjs/common';

export enum ErrorCode {
  VALIDATION_FAILED = 'VALIDATION_FAILED',
  AUTH_INVALID_CREDENTIALS = 'AUTH_INVALID_CREDENTIALS',
  AUTH_TOKEN_INVALID = 'AUTH_TOKEN_INVALID',
  AUTH_TOKEN_EXPIRED = 'AUTH_TOKEN_EXPIRED',
  AUTH_RATE_LIMITED = 'AUTH_RATE_LIMITED',
  FORBIDDEN = 'FORBIDDEN',
  RESOURCE_NOT_FOUND = 'RESOURCE_NOT_FOUND',
  CONFLICT = 'CONFLICT',
  PLATFORM_AUTH_FAILED = 'PLATFORM_AUTH_FAILED',
  PLATFORM_TOKEN_EXPIRED = 'PLATFORM_TOKEN_EXPIRED',
  PLATFORM_PERMISSION_DENIED = 'PLATFORM_PERMISSION_DENIED',
  PLATFORM_RATE_LIMITED = 'PLATFORM_RATE_LIMITED',
  PLATFORM_MEDIA_INVALID = 'PLATFORM_MEDIA_INVALID',
  PLATFORM_CONTENT_REJECTED = 'PLATFORM_CONTENT_REJECTED',
  PLATFORM_API_ERROR = 'PLATFORM_API_ERROR',
  PUBLISH_DUPLICATED = 'PUBLISH_DUPLICATED',
  PUBLISH_TIMEOUT = 'PUBLISH_TIMEOUT',
  CONNECTOR_NOT_FOUND = 'CONNECTOR_NOT_FOUND',
  CONNECTOR_NEEDS_ACTION = 'CONNECTOR_NEEDS_ACTION',
  CRAWLER_URL_BLOCKED = 'CRAWLER_URL_BLOCKED',
  MEDIA_UPLOAD_RATE_LIMITED = 'MEDIA_UPLOAD_RATE_LIMITED',
  INFRASTRUCTURE_UNAVAILABLE = 'INFRASTRUCTURE_UNAVAILABLE',
  INTERNAL_ERROR = 'INTERNAL_ERROR',
}

export class ApplicationException extends HttpException {
  constructor(
    public readonly code: ErrorCode,
    message: string,
    status: HttpStatus = HttpStatus.BAD_REQUEST,
    public readonly details?: unknown,
  ) {
    super({ code, message, details }, status);
  }
}
